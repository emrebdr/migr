package golang

import "fmt"

// SDKPath is the package the generated runner calls, and the one thing this adapter asks of sdk/go.
const SDKPath = "github.com/emrebdr/migr/sdk/go/runner"

// entrypoint is the function that package must export, which speaks the protocol on stdin and stdout.
const entrypoint = "Main"

// generated is the template every runner is written from, taking the migrations import path alone.
const generated = `// Code generated by migr. DO NOT EDIT.

package main

import (
	_ %q

	"%s"
)

func main() { runner.%s() }
`

// generate renders the runner that loads one project's migrations and hands them to the SDK.
func generate(migrations string) []byte {
	return []byte(fmt.Sprintf(generated, migrations, SDKPath, entrypoint))
}

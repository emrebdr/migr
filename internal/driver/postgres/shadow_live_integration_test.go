// A shadow-table migration is held to the done-when here, on postgres17, the compose server running
// wal_level = logical. Eight writers keep a table and an unchanged control table equal, one row of each
// per transaction, from before the copy starts until after the cutover; the migration changes a
// column's type and widens another; and the two tables are compared by row count and checksum once it
// has cut over. A writer that fails is a failure of the migration, however it failed. Some rows carry a
// note large and random enough to be TOASTed out of line, so an update leaving it alone is replayed
// from a change that does not carry it.

// The staged migration's version, which every derived name carries, and the load's shape.
const (
	shadowVersion = "20260927T153000"
	shadowRows    = 20000
	shadowWriters = 8
	hiddenID      = 9000000
)

// logicalServer is the compose server that permits logical decoding.
const logicalServer = 1

// shadowCase is one table changed through a shadow, with everything that watches it.
type shadowCase struct {
	// d is the driver a stream is opened through.
	d driver.Driver
	// dsn is the server's.
	dsn string
	// schema is the scratch schema the case's tables live in.
	schema string
	// c is the session the migration runs on.
	c *pgConn
	// watch is a second session, which reads and confirms the migration's state as an operator would.
	watch *pgConn
	// table is the table the migration changes, and control the one the writers keep equal to it.
	table, control string
}

// newShadowCase opens both sessions on a scratch schema and seeds the table and its control.
func newShadowCase(t *testing.T) *shadowCase {
	t.Helper()

	dsn := dsnFor(servers[logicalServer].env, servers[logicalServer].dsn)
	schema := scratchSchema(t, dsn)
	opts := driver.Options{Schema: schema, HistoryTable: historyTable}

	d, err := New(opts)
	if err != nil {
		t.Fatalf("New: %v", err)
	}

	sc := &shadowCase{d: d, dsn: dsn, schema: schema, c: historyIn(t, dsn, schema), watch: historyIn(t, dsn, schema),
		table: "sh" + digestOf(t.Name())}
	sc.control = sc.table + "_control"

	t.Cleanup(func() { sc.releaseSlot(t) })

	sc.seed(t)

	return sc
}

// releaseSlot drops whatever slot the case's migration made, so a failed case leaves no WAL held.
func (sc *shadowCase) releaseSlot(t *testing.T) {
	t.Helper()

	if err := sc.watch.ReleaseCapture(context.WithoutCancel(t.Context()),
		engine.CaptureName(sc.table, shadowVersion)); err != nil {
		t.Errorf("releasing the case's slot: %v", err)
	}
}

// seed creates the table and its control with the same rows, and leaves the table's identity past every id.
func (sc *shadowCase) seed(t *testing.T) {
	t.Helper()

	for table, id := range map[string]string{sc.table: "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
		sc.control: "bigint PRIMARY KEY"} {
		exec(t, sc.c, "CREATE TABLE "+quote(table)+" (id "+id+", n integer NOT NULL, label varchar(40) NOT NULL, "+
			"at timestamptz NOT NULL, price numeric(10,2), note text, seen timestamp)")
	}

	exec(t, sc.c, "CREATE INDEX "+quote(sc.table+"_label")+" ON "+quote(sc.table)+" (label)")
	exec(t, sc.c, "INSERT INTO "+quote(sc.table)+" (id, n, label, at, price, note) SELECT i, i, 'row ' || i, "+
		"timestamptz '2026-01-01 00:00:00+00' + i * interval '1.000001 second', CASE WHEN i % 7 = 0 THEN NULL "+
		"ELSE i / 100.0 END, CASE WHEN i % 50 = 0 THEN (SELECT string_agg(md5(random()::text || g), '') "+
		"FROM generate_series(1, 300 + i % 3) g) WHEN i % 5 = 0 THEN NULL ELSE repeat('é', i % 9) END "+
		"FROM generate_series(1, "+fmt.Sprint(shadowRows)+") i")
	exec(t, sc.c, "SELECT setval(pg_get_serial_sequence("+quoteLiteral(quote(sc.table))+", 'id'), "+fmt.Sprint(hiddenID)+")")
	exec(t, sc.c, "INSERT INTO "+quote(sc.control)+" SELECT * FROM "+quote(sc.table))
}

// changes are the migration's operations: a column's type changed, and another widened.
func (sc *shadowCase) changes(t *testing.T) ir.Operations {
	t.Helper()

	wide, longer := mustType(t, "int64"), mustType(t, "string(80)")

	return ir.Operations{
		ir.AlterColumn{Table: sc.table, Column: "n", Type: &wide},
		ir.AlterColumn{Table: sc.table, Column: "label", Type: &longer},
	}
}

// options is a run of the staged migration through a shadow table, telling watch about every moment.
func (sc *shadowCase) options(t *testing.T, watch func(engine.ShadowProgress)) engine.Options {
	t.Helper()

	opts := queueOptions(t, staged{version: shadowVersion, name: "change_" + sc.table, ops: sc.changes(t)})
	opts.Online = migration.Online{shadowVersion: migration.ShadowTable}
	opts.Shadower = sc.c
	opts.Capture = func(ctx context.Context, req capture.Request) (capture.Stream, error) {
		return sc.d.Capture(ctx, sc.dsn, req)
	}
	opts.Pacer = engine.Steady{Rows: 500, Pause: 5 * time.Millisecond}
	opts.CaptureLag = 5 * time.Second
	opts.Shadowed = watch

	return opts
}

// writers is the load: each writer owns its keys, and writes one row of the table and its control per transaction.
type writers struct {
	// failed counts every write that did not commit.
	failed atomic.Int64
	// written counts every write that did.
	written atomic.Int64
	// first is the first failure, for the report.
	first atomic.Value
	// stop ends the load.
	stop chan struct{}
	// done is closed once every writer has returned.
	done sync.WaitGroup
}

// startWriters begins the load against a case's table and control.
func (sc *shadowCase) startWriters(t *testing.T) *writers {
	t.Helper()

	w := &writers{stop: make(chan struct{})}

	for i := range shadowWriters {
		conn, err := pgx.Connect(t.Context(), sc.dsn)
		if err != nil {
			t.Fatalf("connecting a writer: %v", err)
		}

		if _, err := conn.Exec(t.Context(), "SET search_path TO "+quote(sc.schema)); err != nil {
			t.Fatalf("pointing a writer at the scratch schema: %v", err)
		}

		w.done.Add(1)

		go func() {
			defer w.done.Done()
			defer func() { _ = conn.Close(context.Background()) }()

			sc.write(w, conn, i)
		}()
	}

	t.Cleanup(w.halt)

	return w
}

// halt ends the load and waits for every writer, once.
func (w *writers) halt() {
	select {
	case <-w.stop:
	default:
		close(w.stop)
	}

	w.done.Wait()
}

// write is one writer: inserts, updates, deletes and key moves over its own rows until the load stops.
func (sc *shadowCase) write(w *writers, conn *pgx.Conn, writer int) {
	var live []int64
	for id := int64(writer + 1); id <= shadowRows; id += shadowWriters {
		live = append(live, id)
	}

	next := int64(1000000 + writer*100000)

	for step := 0; ; step++ {
		select {
		case <-w.stop:
			return
		default:
		}

		statement, args, apply := oneWrite(writer, &live, &next, step)
		if err := sc.writeBoth(conn, statement, args); err != nil {
			w.failed.Add(1)
			w.first.CompareAndSwap(nil, err.Error())

			continue
		}

		apply()
		w.written.Add(1)
	}
}

// oneWrite picks a writer's next write by its step, returning it and what committing it does to its own rows.
func oneWrite(writer int, live *[]int64, next *int64, step int) (string, []any, func()) {
	pick := (step*7919 + writer*104729) % len(*live)
	id := (*live)[pick]

	switch r := (step*31 + writer*17) % 20; {
	case r < 8:
		seen := time.Date(2026, 3, 29, 0, 30, 0, 0, time.UTC).Add(time.Duration(step) * 7 * time.Minute)

		return "UPDATE %s SET n = n + 1, label = $1, price = $2, seen = $3 WHERE id = $4",
			[]any{fmt.Sprintf("upd %d", step), fmt.Sprintf("%d.%02d", step%1000, step%100), seen, id}, func() {}
	case r < 9:
		return "UPDATE %s SET note = $1 WHERE id = $2", []any{strings.Repeat("ü", step%7), id}, func() {}
	case r < 12:
		return "DELETE FROM %s WHERE id = $1", []any{id}, func() {
			*live = append((*live)[:pick], (*live)[pick+1:]...)
		}
	case r < 13:
		*next++
		moved := *next

		return "UPDATE %s SET id = $1 WHERE id = $2", []any{moved, id}, func() { (*live)[pick] = moved }
	default:
		*next++
		created := *next
		at := time.Date(2026, 10, 20, 12, 0, 0, 0, time.UTC).Add(time.Duration(step) * time.Microsecond * 1001)

		return "INSERT INTO %s (id, n, label, at, price, note) VALUES ($1, $2, $3, $4, NULL, 'ok')",
			[]any{created, step, fmt.Sprintf("new %d", step), at}, func() { *live = append(*live, created) }
	}
}

// writeBoth makes one write to the table and the same write to its control, in one transaction.
func (sc *shadowCase) writeBoth(conn *pgx.Conn, statement string, args []any) error {
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()

	tx, err := conn.Begin(ctx)
	if err != nil {
		return err
	}

	for _, table := range []string{sc.table, sc.control} {
		if _, err := tx.Exec(ctx, fmt.Sprintf(statement, quote(table)), args...); err != nil {
			return errors.Join(err, tx.Rollback(ctx))
		}
	}

	return tx.Commit(ctx)
}

// confirmOnce confirms the cutover once the copy has been held in sync for a while, as an operator would.
func (sc *shadowCase) confirmOnce(t *testing.T, held time.Duration) chan struct{} {
	t.Helper()

	done := make(chan struct{})
	store := sc.watch.History().(history.Shadows)

	go func() {
		defer close(done)

		const poll = 100 * time.Millisecond

		var syncing time.Duration

		for range 3000 {
			time.Sleep(poll)

			states, err := store.ShadowStates(context.Background())
			state, found := history.FindShadow(states, shadowVersion)

			switch {
			case err != nil || !found || state.Stage != history.StageSyncing:
				syncing = 0
			case syncing < held:
				syncing += poll
			default:
				_ = store.ConfirmShadow(context.Background(), shadowVersion)

				return
			}
		}
	}()

	return done
}

// rowText renders every column of a row as one string, the way sums checks it.
const rowText = "concat_ws('#', id, n, label, extract(epoch from at), coalesce(price::text, 'null'), " +
	"coalesce(md5(note), 'null'), coalesce(seen::text, 'null'))"

// sums reads a table's row count and a checksum over every column.
func (sc *shadowCase) sums(t *testing.T, table string) string {
	t.Helper()

	var count, sum string

	if err := sc.watch.conn.QueryRow(t.Context(), "SELECT count(*)::text, coalesce(md5(string_agg("+rowText+
		", ',' ORDER BY id)), '') FROM "+quote(table)).Scan(&count, &sum); err != nil {
		t.Fatalf("summing %s: %v", table, err)
	}

	return count + " rows, checksum " + sum
}

// checkEqual holds the table to its control by row count and checksum.
func (sc *shadowCase) checkEqual(t *testing.T) {
	t.Helper()

	if got, want := sc.sums(t, sc.table), sc.sums(t, sc.control); got != want {
		t.Errorf("after the cutover %s holds %s, and the control the writers kept beside it holds %s, "+
			"differing at %v", sc.table, got, want, sc.differing(t))
	}
}

// differing lists a few rows the table and its control disagree on, each side as text.
func (sc *shadowCase) differing(t *testing.T) []string {
	t.Helper()

	rows, err := sc.watch.conn.Query(t.Context(), "SELECT coalesce(a.r, '-') || ' | ' || coalesce(b.r, '-') FROM "+
		"(SELECT id, "+rowText+" AS r FROM "+quote(sc.table)+") a FULL JOIN (SELECT id, "+rowText+" AS r FROM "+
		quote(sc.control)+") b USING (id) WHERE a.r IS DISTINCT FROM b.r LIMIT 5")
	if err != nil {
		t.Fatalf("comparing the rows: %v", err)
	}

	found, err := pgx.CollectRows(rows, pgx.RowTo[string])
	if err != nil {
		t.Fatalf("comparing the rows: %v", err)
	}

	return found
}

// checkLoad fails a case where any write failed, and one where the load wrote nothing.
func checkLoad(t *testing.T, w *writers) {
	t.Helper()

	w.halt()

	if failed := w.failed.Load(); failed > 0 {
		t.Errorf("%d of %d writes failed under the migration, the first: %v", failed, failed+w.written.Load(),
			w.first.Load())
	}

	if w.written.Load() < 100 {
		t.Errorf("the load wrote %d rows, which is no load", w.written.Load())
	}
}

// scalarOf reads one value of a query this test composes, as text.
func (sc *shadowCase) scalarOf(t *testing.T, query string, args ...any) string {
	t.Helper()

	var value string
	if err := sc.watch.conn.QueryRow(t.Context(), query, args...).Scan(&value); err != nil {
		t.Fatalf("%s: %v", query, err)
	}

	return value
}

// checkCutOver holds the table to the migration having changed it under the original's names, kept the original, and left no copy.
func (sc *shadowCase) checkCutOver(t *testing.T) {
	t.Helper()

	for column, want := range map[string]string{"n": "bigint", "label": "character varying(80)"} {
		if got := sc.scalarOf(t, "SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = "+
			"to_regclass(quote_ident($1)) AND attname = $2", sc.table, column); got != want {
			t.Errorf("%s is %s after the cutover, want %s", column, got, want)
		}
	}

	for name, want := range map[string]string{
		engine.ShadowName(sc.table, shadowVersion):  "0",
		engine.RetiredName(sc.table, shadowVersion): "1",
	} {
		if got := sc.scalarOf(t, "SELECT count(*)::text FROM pg_class WHERE relname = $1 AND relnamespace = "+
			"current_schema()::regnamespace", name); got != want {
			t.Errorf("%s is held by %s tables after the cutover, want %s", name, got, want)
		}
	}

	if got := sc.scalarOf(t, "SELECT string_agg(i.relname, ',' ORDER BY i.relname) FROM pg_index x JOIN pg_class i "+
		"ON i.oid = x.indexrelid WHERE x.indrelid = to_regclass(quote_ident($1))", sc.table); got !=
		sc.table+"_label,"+sc.table+"_pkey" {
		t.Errorf("the swapped-in table's indexes are named %s, want the original's names", got)
	}

	if got := sc.scalarOf(t, "SELECT count(*)::text FROM pg_replication_slots WHERE slot_name = $1",
		engine.CaptureName(sc.table, shadowVersion)); got != "0" {
		t.Errorf("the replication slot outlived the cutover")
	}
}

// checkCounter holds the swapped-in table to handing out ids past every one the original ever did.
func (sc *shadowCase) checkCounter(t *testing.T) {
	t.Helper()

	var id int64
	if err := sc.watch.conn.QueryRow(t.Context(), "INSERT INTO "+quote(sc.table)+" (n, label, at) VALUES "+
		"(1, 'auto', now()) RETURNING id").Scan(&id); err != nil {
		t.Fatalf("inserting with a generated id: %v", err)
	}

	if id <= hiddenID {
		t.Errorf("the table handed out id %d after the cutover, which the original had already passed (%d)", id, hiddenID)
	}
}

func TestAColumnTypeChangesThroughAShadowUnderLoadWithNoFailedWriteAndNoLostRow(t *testing.T) {
	sc := newShadowCase(t)
	load := sc.startWriters(t)
	confirmed := sc.confirmOnce(t, 1500*time.Millisecond)

	var positions []string

	opts := sc.options(t, func(p engine.ShadowProgress) { positions = append(positions, p.Position) })

	result, err := engine.Apply(t.Context(), sc.c, opts)
	if err != nil {
		t.Fatalf("Apply: %v", err)
	}

	<-confirmed
	time.Sleep(time.Second)
	checkLoad(t, load)
	sc.checkEqual(t)
	sc.checkCutOver(t)
	sc.checkCounter(t)

	run := result.Runs[0].Shadow
	if run == nil || run.Copied < shadowRows/2 || run.Applied == 0 {
		t.Errorf("the run reported %+v, want the copy and the replay both to have done work", run)
	}

	for _, position := range positions {
		if !strings.Contains(position, "/") {
			t.Errorf("a position was recorded as %q, want a WAL position", position)

			break
		}
	}

	if _, err := engine.Retire(t.Context(), sc.c, opts, shadowVersion); err != nil {
		t.Fatalf("Retire: %v", err)
	}
}

func TestAShadowMigrationStoppedMidCopyOrMidHoldCarriesOnFromItsRecordedPosition(t *testing.T) {
	for name, stop := range map[string]func(engine.ShadowProgress) bool{
		"mid-copy": func(p engine.ShadowProgress) bool { return p.Stage == history.StageCopying && p.Copied >= 4000 },
		"mid-hold": func(p engine.ShadowProgress) bool { return p.Holding },
	} {
		t.Run(name, func(t *testing.T) {
			sc := newShadowCase(t)
			load := sc.startWriters(t)

			ctx, cancel := context.WithCancel(t.Context())
			defer cancel()

			_, err := engine.Apply(ctx, sc.c, sc.options(t, func(p engine.ShadowProgress) {
				if stop(p) {
					cancel()
				}
			}))
			if !errors.Is(err, context.Canceled) {
				t.Fatalf("the stopped run returned %v, want it canceled", err)
			}

			if got := sc.scalarOf(t, "SELECT count(*)::text FROM pg_replication_slots WHERE slot_name = $1",
				engine.CaptureName(sc.table, shadowVersion)); got != "1" {
				t.Fatalf("stopping the run left %s slots, want its own kept for the resume", got)
			}

			confirmed := sc.confirmOnce(t, time.Second)

			var resumed bool

			if _, err := engine.Apply(t.Context(), sc.c, sc.options(t, func(p engine.ShadowProgress) {
				resumed = resumed || p.Resumed
			})); err != nil {
				t.Fatalf("the resumed Apply: %v", err)
			}

			<-confirmed
			checkLoad(t, load)
			sc.checkEqual(t)
			sc.checkCutOver(t)

			if !resumed {
				t.Error("the second run did not report carrying the first on")
			}
		})
	}
}

// abandon settles a stopped shadow-table migration as rolled back, as migr resolve --rolled-back does.
func (sc *shadowCase) abandon(t *testing.T) {
	t.Helper()

	if _, err := engine.Resolve(t.Context(), sc.c, sc.options(t, nil), engine.Repair{Mode: engine.RepairRolledBack,
		Reason: "abandoned by the test"}); err != nil {
		t.Fatalf("Resolve --rolled-back: %v", err)
	}
}

// checkAbandoned holds an abandoned migration to leaving the table as it was and nothing of its own behind.
func (sc *shadowCase) checkAbandoned(t *testing.T) {
	t.Helper()

	name := engine.CaptureName(sc.table, shadowVersion)

	for query, what := range map[string]string{
		"SELECT count(*)::text FROM pg_replication_slots WHERE slot_name = $1": "replication slot",
		"SELECT count(*)::text FROM pg_publication WHERE pubname = $1":         "publication",
	} {
		if got := sc.scalarOf(t, query, name); got != "0" {
			t.Errorf("abandoning left the %s %s behind", what, name)
		}
	}

	if got := sc.scalarOf(t, "SELECT count(*)::text FROM pg_class WHERE relname = $1 AND relnamespace = "+
		"current_schema()::regnamespace", engine.ShadowName(sc.table, shadowVersion)); got != "0" {
		t.Error("abandoning left the copy behind")
	}

	states, err := sc.watch.History().(history.Shadows).ShadowStates(t.Context())
	if _, found := history.FindShadow(states, shadowVersion); err != nil || found {
		t.Errorf("abandoning left the state row behind (%v)", err)
	}
}

func TestAbandoningAShadowMigrationAtAnyStageLeavesNoCopyNoSlotNoPublicationAndNoState(t *testing.T) {
	for name, stop := range map[string]func(engine.ShadowProgress) bool{
		"copying": func(p engine.ShadowProgress) bool { return p.Stage == history.StageCopying && p.Copied > 0 },
		"syncing": func(p engine.ShadowProgress) bool { return p.Holding },
	} {
		t.Run(name, func(t *testing.T) {
			sc := newShadowCase(t)
			load := sc.startWriters(t)

			ctx, cancel := context.WithCancel(t.Context())
			defer cancel()

			_, err := engine.Apply(ctx, sc.c, sc.options(t, func(p engine.ShadowProgress) {
				if stop(p) {
					cancel()
				}
			}))
			if !errors.Is(err, context.Canceled) {
				t.Fatalf("the stopped run returned %v, want it canceled", err)
			}

			sc.abandon(t)
			checkLoad(t, load)
			sc.checkAbandoned(t)
			sc.checkEqual(t)
		})
	}
}

func TestATableAlteredOrTruncatedUnderAHeldShadowStopsTheMigrationNamingIt(t *testing.T) {
	for name, statement := range map[string]string{
		"altered":   "ALTER TABLE %s ADD COLUMN extra integer",
		"truncated": "TRUNCATE %s",
	} {
		t.Run(name, func(t *testing.T) {
			sc := newShadowCase(t)
			changed := false

			_, err := engine.Apply(t.Context(), sc.c, sc.options(t, func(p engine.ShadowProgress) {
				if p.Holding && !changed {
					changed = true

					if _, err := sc.watch.conn.Exec(context.Background(), fmt.Sprintf(statement, quote(sc.table))); err != nil {
						t.Errorf("changing the table under the hold: %v", err)
					}

					if _, err := sc.watch.conn.Exec(context.Background(), "INSERT INTO "+quote(sc.table)+
						" (n, label, at) VALUES (1, 'after', now())"); err != nil {
						t.Errorf("writing after the change: %v", err)
					}
				}
			}))
			if !errors.Is(err, errReshaped) && !errors.Is(err, errTruncated) {
				t.Fatalf("Apply returned %v, want the stream to stop naming the change", err)
			}

			sc.abandon(t)
			sc.checkAbandoned(t)
		})
	}
}

func TestAStartKilledBeforeItsRecordLeavesASlotTheNextRunDropsAndRemakes(t *testing.T) {
	sc := newShadowCase(t)
	name := engine.CaptureName(sc.table, shadowVersion)

	stream, err := sc.d.Capture(t.Context(), sc.dsn, capture.Request{Name: name, Tables: []string{sc.table}})
	if err != nil {
		t.Fatalf("staging the slot a killed start left: %v", err)
	}

	if err := stream.Close(t.Context()); err != nil {
		t.Fatalf("Close: %v", err)
	}

	confirmed := sc.confirmOnce(t, 500*time.Millisecond)

	if _, err := engine.Apply(t.Context(), sc.c, sc.options(t, nil)); err != nil {
		t.Fatalf("the run after the killed start: %v", err)
	}

	<-confirmed
	sc.checkEqual(t)
	sc.checkCutOver(t)
}

func TestASlotACutoverLeftAndAStrangersAreToldApartAndOnlyOursIsReleased(t *testing.T) {
	sc := newShadowCase(t)
	ours := engine.CaptureName(sc.table, shadowVersion)
	stranger := "migr_20990101t000000_" + digestOf(t.Name())

	for _, name := range []string{ours, stranger} {
		stream, err := sc.d.Capture(t.Context(), sc.dsn, capture.Request{Name: name, Tables: []string{sc.table}})
		if err != nil {
			t.Fatalf("staging the slot %s: %v", name, err)
		}

		if err := stream.Close(t.Context()); err != nil {
			t.Fatalf("Close: %v", err)
		}
	}

	t.Cleanup(func() { _ = sc.watch.ReleaseCapture(context.WithoutCancel(t.Context()), stranger) })

	opts := sc.options(t, nil)
	opts.Unattended = true

	var released []string

	opts.Released = func(r engine.ReleasedCapture) { released = append(released, r.Orphan.Resource.Name) }

	result, err := engine.Apply(t.Context(), sc.c, opts)
	if err != nil {
		t.Fatalf("Apply: %v", err)
	}

	if len(released) != 1 || released[0] != ours || len(result.Released) != 1 {
		t.Errorf("the run released %v, want exactly %s", released, ours)
	}

	if got := sc.scalarOf(t, "SELECT count(*)::text FROM pg_replication_slots WHERE slot_name = $1", stranger); got != "1" {
		t.Error("the run dropped a slot named for a migration this project does not carry")
	}

	resources, err := sc.watch.CaptureResources(t.Context())
	if err != nil {
		t.Fatalf("CaptureResources: %v", err)
	}

	orphans := engine.Orphans(resources, nil, nil)

	found := false

	for _, o := range orphans {
		if o.Resource.Name == stranger && !o.Ours {
			found = true
		}
	}

	if !found {
		t.Errorf("the stranger slot is not reported as an orphan someone else must drop: %+v", orphans)
	}
}

func TestATableThatCannotBeShadowedIsRefusedNamingWhy(t *testing.T) {
	for name, tc := range map[string]struct {
		setup []string
		says  string
	}{
		"a foreign key into it": {setup: []string{"CREATE TABLE %[1]s_child (id bigint PRIMARY KEY, p bigint REFERENCES %[1]s (id))"},
			says: "takes part in the foreign keys"},
		"a view over it":  {setup: []string{"CREATE VIEW %[1]s_view AS SELECT id FROM %[1]s"}, says: "is read by"},
		"a trigger on it": {setup: []string{"CREATE FUNCTION %[1]s_noop() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$", "CREATE TRIGGER t BEFORE UPDATE ON %[1]s FOR EACH ROW EXECUTE FUNCTION %[1]s_noop()"}, says: "has the triggers"},
		"row security":    {setup: []string{"ALTER TABLE %[1]s ENABLE ROW LEVEL SECURITY"}, says: "row-level security"},
		"replica identity nothing": {setup: []string{"ALTER TABLE %[1]s REPLICA IDENTITY NOTHING"},
			says: "REPLICA IDENTITY NOTHING"},
	} {
		t.Run(name, func(t *testing.T) {
			sc := newShadowCase(t)

			for _, statement := range tc.setup {
				exec(t, sc.c, fmt.Sprintf(statement, sc.table))
			}

			err := sc.c.Admits(t.Context(), driver.Shadow{Table: sc.table})
			if err == nil || !strings.Contains(err.Error(), tc.says) {
				t.Errorf("Admits returned %v, want it to say %q", err, tc.says)
			}
		})
	}
}

func TestGrantsAndAToastedNoteSurviveTheCutover(t *testing.T) {
	sc := newShadowCase(t)

	exec(t, sc.c, "DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'migr_reader') THEN "+
		"CREATE ROLE migr_reader; END IF; END $$")
	exec(t, sc.c, "GRANT SELECT ON "+quote(sc.table)+" TO migr_reader")
	exec(t, sc.c, "GRANT UPDATE (label) ON "+quote(sc.table)+" TO migr_reader")

	before := sc.scalarOf(t, "SELECT md5(note) FROM "+quote(sc.table)+" WHERE id = 50")

	updated := false

	opts := sc.options(t, func(p engine.ShadowProgress) {
		if p.Holding && !updated {
			updated = true

			exec(t, sc.watch, "UPDATE "+quote(sc.table)+" SET n = n + 1 WHERE id = 50")
		}
	})
	opts.Unattended = true

	if _, err := engine.Apply(t.Context(), sc.c, opts); err != nil {
		t.Fatalf("Apply: %v", err)
	}

	if got := sc.scalarOf(t, "SELECT md5(note) FROM "+quote(sc.table)+" WHERE id = 50"); got != before {
		t.Errorf("a TOASTed note an update left alone changed across the cutover")
	}

	if got := sc.scalarOf(t, "SELECT has_table_privilege('migr_reader', to_regclass(quote_ident($1)), 'SELECT')::text",
		sc.table); got != "true" {
		t.Error("the table's grant did not survive the cutover")
	}

	if got := sc.scalarOf(t, "SELECT has_column_privilege('migr_reader', to_regclass(quote_ident($1)), 'label', 'UPDATE')::text",
		sc.table); got != "true" {
		t.Error("the column grant did not survive the cutover")
	}
}

func TestACopyWaitsOutADeleteThatHasNotCommittedAndCopiesNothingOfIt(t *testing.T) {
	sc := newShadowCase(t)
	shadow := driver.Shadow{Table: sc.table, Shadow: engine.ShadowName(sc.table, shadowVersion),
		Retired: engine.RetiredName(sc.table, shadowVersion), Key: []string{"id"}}

	stmts, err := sc.c.CreateShadow(t.Context(), shadow)
	if err != nil {
		t.Fatalf("CreateShadow: %v", err)
	}

	for _, stmt := range stmts {
		if err := sc.c.Exec(t.Context(), stmt); err != nil {
			t.Fatalf("%s: %v", stmt.SQL, err)
		}
	}

	deleter, err := pgx.Connect(t.Context(), sc.dsn)
	if err != nil {
		t.Fatalf("connecting the deleter: %v", err)
	}

	defer func() { _ = deleter.Close(context.Background()) }()

	tx, err := deleter.Begin(t.Context())
	if err != nil {
		t.Fatal(err)
	}

	if _, err := tx.Exec(t.Context(), "DELETE FROM "+quote(sc.schema)+"."+quote(sc.table)+" WHERE id = 5"); err != nil {
		t.Fatalf("deleting under an open transaction: %v", err)
	}

	committed := make(chan error, 1)

	go func() {
		time.Sleep(time.Second)
		committed <- tx.Commit(context.Background())
	}()

	if err := sc.c.Transact(t.Context(), func(ctx context.Context) error {
		_, err := sc.c.CopyChunk(ctx, shadow, nil, 10)

		return err
	}); err != nil {
		t.Fatalf("CopyChunk: %v", err)
	}

	if err := <-committed; err != nil {
		t.Fatalf("committing the delete: %v", err)
	}

	if got := sc.scalarOf(t, "SELECT count(*)::text FROM "+quote(shadow.Shadow)+" WHERE id = 5"); got != "0" {
		t.Error("the copy took a row whose delete was in flight, which a replay of that delete may already have passed")
		t.Log("FOR SHARE is what makes the copy wait for the deleter and skip the row once it commits;")
		t.Log("without it the copy reads the row as its snapshot still sees it.")
	}
}
